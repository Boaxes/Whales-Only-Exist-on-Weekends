"""Write CREDITS.md: every dataset that contributed a whale record, with its licence, citation and record counts.

Reads WHALES.MARTS for the record counts, and each dataset's licence and citation from its OBIS API record in
WHALES.RAW.OBIS_DATASET, through the `whales` Snowflake connection.
Usage: uv run python make_credits.py
"""
import collections
import html
import re
from pathlib import Path

import snowflake.connector

ROOT = Path(__file__).resolve().parent
QUERY = '''
SELECT
    dim_dataset.title,
    dim_dataset.kind,
    obis_dataset.api_record:intellectualrights::STRING AS licence,
    obis_dataset.api_record:citation::STRING AS citation,
    obis_dataset.url,
    COUNT(*) AS records,
    COUNT_IF(dim_location.in_bay) AS bay_records
FROM whales.marts.fct_sighting AS fct_sighting
JOIN whales.marts.dim_dataset AS dim_dataset ON dim_dataset.dataset_key = fct_sighting.dataset_key
JOIN whales.marts.dim_location AS dim_location ON dim_location.location_key = fct_sighting.location_key
JOIN whales.raw.obis_dataset AS obis_dataset ON obis_dataset.dataset_id = dim_dataset.dataset_id
GROUP BY dim_dataset.title, dim_dataset.kind, licence, citation, obis_dataset.url
ORDER BY records DESC, dim_dataset.title
'''
LICENCE_URL = {'CC BY-NC 4.0': 'https://creativecommons.org/licenses/by-nc/4.0/', 'CC BY 4.0': 'https://creativecommons.org/licenses/by/4.0/',
               'CC0 1.0': 'https://creativecommons.org/publicdomain/zero/1.0/'}


def licence_name(text):
    """The OBIS licence sentence, shortened to its name."""
    t = (text or '').replace('  ', ' ')
    if 'Non Commercial' in t:
        return 'CC BY-NC 4.0'
    if 'CC0' in t or 'Public Domain' in t:
        return 'CC0 1.0'
    if 'Attribution' in t:
        return 'CC BY 4.0'
    return 'not stated'


def clean(text):
    """Undo the escaping some citations carry in the OBIS metadata."""
    return html.unescape(re.sub(r"\\'|''", "'", (text or '').strip())).replace('|', '/')


with snowflake.connector.connect(connection_name='whales', warehouse='WHALES_WH') as connection:
    rows = connection.cursor(snowflake.connector.DictCursor).execute(QUERY).fetchall()

total = sum(r['RECORDS'] for r in rows)
bay = sum(r['BAY_RECORDS'] for r in rows)
by_licence = collections.Counter(licence_name(r['LICENCE']) for r in rows)

lines = [
    '# Credits',
    '',
    'This project uses only openly published data. Thank you to every observer, survey team and data publisher below.',
    '',
    '## Whale records (OBIS)',
    '',
    f'All whale records come from the [Ocean Biodiversity Information System](https://obis.org) open-data archive '
    f'(`s3://obis-open-data/`): {total:,} cetacean records from {len(rows)} datasets in the West Coast box '
    f'(32 to 49.5 N, 130 to 116 W), {bay:,} of them in the Monterey Bay box. Each dataset keeps its own licence: '
    + ', '.join(f'{n} ({c} dataset{"" if c == 1 else "s"})' for n, c in sorted(by_licence.items(), key=lambda kv: -kv[1])) + '. '
    'The CC BY-NC data (including Happywhale and iNaturalist) is used here for a non-commercial portfolio, with credit.',
    '',
    'Generated by `make_credits.py` from `WHALES.MARTS` and the OBIS API records. Records are counted after dbt cleaning.',
    '',
    '| Dataset | Kind | Licence | Records | In the bay | Citation |',
    '|---|---|---|--:|--:|---|',
]
for r in rows:
    title = clean(r['TITLE'])
    title = f'[{title}]({r["URL"]})' if r['URL'] else title
    lic = licence_name(r['LICENCE'])
    lic = f'[{lic}]({LICENCE_URL[lic]})' if lic in LICENCE_URL else lic
    lines.append(f'| {title} | {r["KIND"]} | {lic} | {r["RECORDS"]:,} | {r["BAY_RECORDS"]:,} | {clean(r["CITATION"])} |')

lines += [
    '',
    '## Other data',
    '',
    '| Source | Used for | Terms |',
    '|---|---|---|',
    '| [iNaturalist Open Data](https://github.com/inaturalist/inaturalist-open-data) (`s3://inaturalist-open-data/`, `observations.csv.gz`) | Observers out per day around the bay (notebook 05) | See the iNaturalist Open Data licence notes at the link |',
    '| [US Census Bureau cartographic boundary files](https://www.census.gov/geographies/mapping-files/time-series/geo/cartographic-boundary.html), 2023, states, 1:500,000 | Coastline behind the Power BI map | Public domain |',
    '| [Monterey Bay Whale Watch](https://montereybaywhalewatch.com/schedule/) published schedule, read 16 October 2026 | Trip times in notebook 03 | Cited, not copied |',
    '| [Monterey Bay Whale Watch sightings log, June 2020](https://montereybaywhalewatch.com/sightings/slst2006/), read 16 October 2026 | Dates of the 2020 shutdown in notebook 05 | Cited, not copied |',
    '| US federal holiday calendar (observed dates, 2010 to 2026) | Holiday comparison in notebook 02 | Public facts, typed into a dbt seed |',
    '',
    '## Software',
    '',
    'Snowflake (storage, dbt runs, Snowflake Notebooks), dbt Core with dbt-snowflake, the Snowflake Python connector, '
    'marimo for the static notebooks, and Power BI Desktop. The design of the Power BI report borrows its '
    'colours and type (Archivo, IBM Plex Mono) from the author\'s Salish project.',
    '',
]
(ROOT / 'CREDITS.md').write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(rows)} datasets, {total:,} records -> CREDITS.md')
